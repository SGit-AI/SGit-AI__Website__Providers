#!/usr/bin/env python3
"""Refresh data/providers.yml from the provider sites themselves.

    bin/sync-providers.py            fetch and rewrite data/providers.yml
    bin/sync-providers.py --check    fetch and report drift, change nothing

This hub keeps no opinion of its own about a provider. Each provider site publishes
two things for its own purposes — the markdown twin of its report (which carries the
`patterns:` front-matter) and the claim index its ask pane matches against — and this
script reads those. So a row here can only be wrong if it is wrong on the provider's
own page first, which is where a correction belongs.

The build never does this. A sync is a deliberate, dated act, the date is printed
wherever the data appears, and the site builds offline and reproducibly in CI.
"""
import json
import re
import sys
import urllib.error
import urllib.request
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "providers.yml"
UA = {"User-Agent": "providers.sgit.ai sync (+https://providers.sgit.ai)"}


def fetch(url):
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read().decode("utf-8")


def serves(base, marker):
    """Does this host actually serve this site right now?

    Not "does the name resolve" — a canonical domain can resolve to the Pages
    edge and still 404, or redirect somewhere else entirely, and either way the
    link is dead. So the probe fetches the site's own published index from that
    host and requires a marker only that site's index carries. `live:` in
    providers.yml is the result of this call, which is why the pages can carry a
    dated claim about it rather than a promise."""
    try:
        idx = json.loads(fetch(f"{base.rstrip('/')}/assets/site-index.json"))
    except (urllib.error.URLError, OSError, ValueError):
        return False
    return marker in json.dumps(idx, ensure_ascii=False)


def front_matter(md):
    """The provider page's own front-matter, verbatim, as text — re-emitted into
    providers.yml rather than re-typed, so the two cannot drift silently."""
    if not md.startswith("---"):
        return ""
    return md.split("---", 2)[1]


def indent(block, spaces):
    pad = " " * spaces
    return "\n".join(pad + line if line.strip() else "" for line in block.strip("\n").split("\n"))


def main():
    check = "--check" in sys.argv
    sites = [
        # name, canonical host, the project path to fall back to, a string that
        # proves the host is serving THIS site, kind, summary
        ("ElevenLabs", "https://elevenlabs.providers.sgit.ai",
         "https://sgit-ai.github.io/SGit-AI__Website__Provider__ElevenLabs",
         "ElevenLabs \u2014 text to speech",
         "voice · text to speech",
         "Text to speech with character-level timestamps. Scoped keys, no per-key spend limit, "
         "and the first render's four failures."),
    ]
    planned = [
        ("OpenRouter", "https://openrouter.providers.sgit.ai", "", "models · one API, many models",
         "Provisioned keys with a spend limit and a reset — the one provider in this family that "
         "can do pattern one. Not built yet."),
    ]

    out = [
        "# Generated by bin/sync-providers.py — do not edit by hand.",
        "#",
        "# Each provider's `patterns:` block is copied verbatim from that site's own",
        "# published markdown twin. Its claim counts come from that site's published",
        "# claim index. This hub adds nothing except the family metadata.",
        f"synced: {date.today().isoformat()}",
        "providers:",
    ]
    for name, canonical, fallback, marker, kind, summary in sites:
        # The canonical host wins the moment it actually serves the site; until
        # then the fallback does, and the yml records which — dated, so the pages
        # can say it rather than assume it.
        canonical_live = serves(canonical, marker)
        live = canonical if canonical_live else fallback
        base = live.rstrip("/")
        md = fetch(f"{base}/index.md")
        fm = front_matter(md)
        pat = re.search(r"^patterns:\n(.*?)(?=^\w|\Z)", fm, re.S | re.M)
        idx = json.loads(fetch(f"{base}/assets/site-index.json"))
        counts = {}
        for c in idx.get("claims", []):
            counts[c["state"]] = counts.get(c["state"], 0) + 1
        out += [
            f"  - name: {name}",
            f"    canonical: {canonical}",
            f"    live: {live}",
            f"    canonical_resolves: {'yes' if canonical_live else 'no'}",
            f"    kind: {kind}",
            f'    summary: "{summary}"',
            "    state: live",
            f"    site_version: {idx.get('version', '?')}",
            "    state_chips: [verified, measured, docs]",
            "    claims:",
        ] + [f"      {k}: {v}" for k, v in sorted(counts.items())]
        if pat:
            out += ["    patterns:", indent(pat.group(1), 6)]
    for name, canonical, live, kind, summary in planned:
        out += [
            f"  - name: {name}",
            f"    canonical: {canonical}",
            f"    live: {live or canonical}",
            "    canonical_resolves: no",
            f"    kind: {kind}",
            f'    summary: "{summary}"',
            "    state: planned",
            "    state_chips: [spec]",
        ]
    text = "\n".join(out) + "\n"

    if check:
        current = DATA.read_text() if DATA.exists() else ""
        drift = [l for l in text.split("\n") if l not in current.split("\n") and not l.startswith("synced:")]
        print("sync --check: drift" if drift else "sync --check: providers.yml matches the sites")
        for d in drift[:20]:
            print("  " + d)
        return 1 if drift else 0
    DATA.write_text(text)
    print(f"synced {len(sites)} live and {len(planned)} planned provider(s) -> {DATA.relative_to(ROOT)}")
    for line in text.split("\n"):
        if line.strip().startswith(("live:", "canonical_resolves:")):
            print("  " + line.strip())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
